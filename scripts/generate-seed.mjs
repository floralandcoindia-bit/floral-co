// Turns src/data/products.js + collections.js into supabase/02_seed.sql (run: node scripts/generate-seed.mjs)
import { readFileSync, writeFileSync } from "node:fs";

// The data files import a browser helper without a file extension, which plain Node can't resolve.
// Images are not seeded, so we load the files with that import swapped for a stub.
const load = async (file) => {
  const src = readFileSync(new URL(`../src/data/${file}`, import.meta.url), "utf8").replace(
    /import \{ makePlaceholder \} from .*;/,
    "const makePlaceholder = () => '';"
  );
  return import(`data:text/javascript;base64,${Buffer.from(src).toString("base64")}`);
};
const { products } = await load("products.js");
const { collections } = await load("collections.js");

const q = (v) => (v === null || v === undefined ? "null" : `'${String(v).replace(/'/g, "''")}'`);
const json = (v) => `${q(JSON.stringify(v))}::jsonb`;
const arr = (a) => `array[${a.map(q).join(",")}]::text[]`;

let sql = `-- Seed: your original sample products and collections (generated by scripts/generate-seed.mjs).
-- Run AFTER 01_schema.sql. Safe to re-run (it updates rows with the same id).
-- Products have no photos yet: the shop shows a tidy placeholder until you upload real ones in /admin.

`;
sql += "insert into public.collections (id, slug, title, description, cover_url, theme, sort_order) values\n";
sql += collections
  .map((c, i) => `  (${q(c.id)}, ${q(c.slug)}, ${q(c.title)}, ${q(c.description)}, null, ${json(c.theme)}, ${i + 1})`)
  .join(",\n");
sql += `\non conflict (id) do update set slug = excluded.slug, title = excluded.title, description = excluded.description,
  theme = excluded.theme, sort_order = excluded.sort_order;\n\n`;

sql += "insert into public.products (id, slug, name, description, price, category, collection_slug, images, featured, trending, is_available, keywords, customisation_options, created_at) values\n";
sql += products
  .map(
    (p) =>
      `  (${q(p.id)}, ${q(p.slug)}, ${q(p.name)}, ${q(p.description)}, ${p.price}, ${q(p.category)}, ${q(p.collection)}, '[]'::jsonb, ${p.featured}, ${p.trending}, ${p.isAvailable}, ${arr(p.keywords || [])}, ${json(p.customisationOptions || [])}, ${q(p.createdAt)})`
  )
  .join(",\n");
sql += `\non conflict (id) do update set slug = excluded.slug, name = excluded.name, description = excluded.description,
  price = excluded.price, category = excluded.category, collection_slug = excluded.collection_slug,
  featured = excluded.featured, trending = excluded.trending, is_available = excluded.is_available,
  keywords = excluded.keywords, customisation_options = excluded.customisation_options;\n`;

writeFileSync(new URL("../supabase/02_seed.sql", import.meta.url), sql);
console.log(`Wrote supabase/02_seed.sql (${products.length} products, ${collections.length} collections)`);
